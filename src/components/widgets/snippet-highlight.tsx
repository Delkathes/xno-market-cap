import { useMemo } from 'react'

type SnippetToken = { type: 'tag' | 'punct' | 'attr' | 'str' | 'plain'; text: string }

// Tokenizer for the embed snippet: a fixed template of tags, attributes and
// quoted strings. Tag names include their `<` (or `</`), attribute names
// carry their `=`, boolean attributes (`defer`) fall through to the bare-word
// alternative. Anything unmatched (whitespace, stray characters) is plain.
const SNIPPET_TOKENIZER = /<\/?[a-zA-Z][\w-]*|\/?>|[\w-]+=|"[^"]*"|'[^']*'|[\w-]+|\s+|./g

function tokenizeSnippet(code: string): SnippetToken[] {
	const tokens: SnippetToken[] = []
	for (const match of code.matchAll(SNIPPET_TOKENIZER)) {
		const text = match[0]
		if (text.startsWith('<')) tokens.push({ type: 'tag', text })
		else if (text === '>' || text === '/>') tokens.push({ type: 'punct', text })
		else if (text.endsWith('=')) tokens.push({ type: 'attr', text })
		else if (text.startsWith('"') || text.startsWith("'")) tokens.push({ type: 'str', text })
		else if (/^[\w-]+$/.test(text)) tokens.push({ type: 'attr', text })
		else tokens.push({ type: 'plain', text })
	}
	return tokens
}

const TOKEN_CLASS: Record<SnippetToken['type'], string> = {
	tag: 'text-[#209CE9]',
	punct: 'text-muted-foreground/50',
	attr: 'text-violet-500 dark:text-violet-400',
	str: 'text-amber-600 dark:text-amber-400',
	plain: 'text-muted-foreground/70',
}

/**
 * Lightweight syntax highlighting for the embed snippet (no library: the
 * markup is generated by us, so a tiny regex tokenizer is exact). Text is
 * rendered as React children, so everything is escaped by React itself.
 */
export function HighlightedSnippet({ code }: { code: string }) {
	const tokens = useMemo(() => tokenizeSnippet(code), [code])
	return (
		<>
			{tokens.map((token, index) => (
				// biome-ignore lint/suspicious/noArrayIndexKey: deterministic token list, order never changes, and token text can repeat (`=`).
				<span key={index} className={TOKEN_CLASS[token.type]}>
					{token.text}
				</span>
			))}
		</>
	)
}
